def mname(path):
    parts = re.split(r"[^A-Za-z0-9]+", path)
    s = "".join(p[:1].upper() + p[1:] for p in parts if p)
    return "".join(DIG.get(ch, ch) for ch in s)


def neg(s):
    """Typeset minus signs properly."""
    return re.sub(r"-(?=\d)", "$-$", s)


def fint(n):
    return f"{int(round(n)):,}".replace(",", "{,}")


def ffloat(x, nd=2):
    return f"{x:.{nd}f}"


def tex_name(s):
    return s.replace("\\", " + ").replace("&", r"\&").replace("%", r"\%").replace("_", r"\_").capitalize()


class Macros:
    def __init__(self):
        self.d = {}

    def add(self, name, val):
        name = mname(name)
        if name in self.d and self.d[name] != val:
            raise ValueError(f"macro clash {name}")
        self.d[name] = val

    def est(self, name, e):
        if not e or e.get("or") is None:
            return
        self.add(name, f"{e['or']:.2f} (95\\% CI {e['lo']:.2f} to {e['hi']:.2f})")
        self.add(name + "OR", f"{e['or']:.2f}")
        self.add(name + "CI", f"{e['lo']:.2f} to {e['hi']:.2f}")

    def walk(self, prefix, obj):
        if isinstance(obj, dict):
            if "rd" in obj and "lo" in obj and "hi" in obj:
                self.add(prefix, neg(f"{100 * obj['rd']:.2f} points (95\\% CI {100 * obj['lo']:.2f} to {100 * obj['hi']:.2f})"))
                self.add(prefix + "PT", neg(f"{100 * obj['rd']:.2f}"))
                return
            if "or" in obj and "lo" in obj and "hi" in obj:
                self.est(prefix, obj)
                for k in ("female_cases", "female_n", "male_cases", "male_n", "informative_strata"):
                    if k in obj:
                        self.add(prefix + "." + k, fint(obj[k]))
                return
            for k, v in obj.items():
                self.walk(prefix + "." + str(k), v)
        elif isinstance(obj, bool):
            return
        elif isinstance(obj, int):
            self.add(prefix, fint(obj))
        elif isinstance(obj, float):
            self.add(prefix, ffloat(obj, 3) if abs(obj) < 10 else fint(obj))

    def write(self, path):
        with open(path, "w") as f:
            f.write("% Generated by scripts/08_tables.py. Do not edit by hand.\n")
            for k in sorted(self.d):
                f.write(f"\\newcommand{{\\{k}}}{{{self.d[k]}}}\n")


